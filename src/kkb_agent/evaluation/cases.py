"""Fixed finance-semantic cases and independent EVAL-SMOKE oracles.

The production functions below calculate only actual results. Expected values
are literal hand calculations recorded in each ``OracleRecord``; none is
generated by calling the implementation under test.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from datetime import date
from typing import Literal

from kkb_agent.analytics.comovement import co_movement
from kkb_agent.analytics.deflation import FORMULA, deflate
from kkb_agent.analytics.table_relationship import compare_table_directions
from kkb_agent.analytics.table_series import add_monthly_series
from kkb_agent.core import (
    Aggregation,
    AnalyticalResult,
    CumulativeKind,
    Frequency,
    Period,
    ResultEvidence,
    ResultKind,
    ResultStatus,
    ResultValue,
    Scale,
    StockFlow,
)
from kkb_agent.evaluation.models import OracleRecord
from kkb_agent.lakehouse.records import Observation
from kkb_agent.lakehouse.semantics import SeriesSemantics

Operation = Literal["monthly_co_movement", "deflate", "add_series", "table_co_movement", "abstain"]
Actual = dict[str, object]

MONTHS = (date(2021, 1, 31), date(2021, 2, 28), date(2021, 3, 31), date(2021, 4, 30))
CREDIT_LABEL = "housing_credit_balance"
RATE_LABEL = "housing_loan_rate"
CPI_ID = "synthetic_cpi_2025"
KFE_ID = "synthetic_national_kfe"

RATE = SeriesSemantics(
    unit="percent",
    scale=Scale.ONE,
    frequency=Frequency.MONTHLY,
    observation=StockFlow.RATE,
    cumulative=CumulativeKind.NONE,
    aggregation=Aggregation.AVERAGE,
)
STOCK = SeriesSemantics(
    unit="TRY",
    scale=Scale.MILLION,
    frequency=Frequency.MONTHLY,
    observation=StockFlow.STOCK,
    cumulative=CumulativeKind.NONE,
)
CPI = SeriesSemantics(
    unit="index",
    scale=Scale.ONE,
    frequency=Frequency.MONTHLY,
    observation=StockFlow.INDEX,
    cumulative=CumulativeKind.NONE,
    base_year=2025,
)
KFE = SeriesSemantics(
    unit="index",
    scale=Scale.ONE,
    frequency=Frequency.MONTHLY,
    observation=StockFlow.INDEX,
    cumulative=CumulativeKind.NONE,
    base_year=2017,
)


@dataclass(frozen=True, slots=True)
class CaseSpec:
    """One executable actual path paired with an independently authored oracle."""

    case_id: str
    category: str
    turn: int | None
    question: str
    operation: Operation
    input_fixture: dict[str, object]
    expected: dict[str, object]
    oracle: OracleRecord
    execute: Callable[[], Actual]


def _observations(values: tuple[float | None, ...]) -> list[Observation]:
    return [
        Observation(end.replace(day=1), end, value)
        for end, value in zip(MONTHS, values, strict=True)
    ]


def _period(end: date) -> Period:
    return Period(start=end.replace(day=1), end=end, frequency=Frequency.MONTHLY)


def _column(label: str, values: tuple[float, ...], semantics: SeriesSemantics) -> list[ResultValue]:
    return [
        ResultValue(
            label=label,
            value=value,
            unit=semantics.unit,
            scale=semantics.scale,
            measure=semantics.observation,
            period=_period(end),
        )
        for end, value in zip(MONTHS, values, strict=True)
    ]


def _table(
    credit: tuple[float, ...] = (100.0, 110.0, 105.0, 120.0),
    rate: tuple[float, ...] = (10.0, 9.0, 8.5, 9.0),
) -> AnalyticalResult:
    return AnalyticalResult(
        result_id="synthetic_housing_table",
        kind=ResultKind.SERIES,
        status=ResultStatus.COMPUTED,
        tool="fixture",
        method="fixed-hand-authored-v1",
        values=[*_column(CREDIT_LABEL, credit, STOCK), *_column(RATE_LABEL, rate, RATE)],
        coverage=Period(start=date(2021, 1, 1), end=MONTHS[-1], frequency=Frequency.MONTHLY),
        evidence=ResultEvidence(input_refs=["synthetic_fixed_input"]),
        limitations=[
            "Values are nominal; no inflation adjustment was applied",
            "Housing credit is an outstanding stock, not lending disbursement",
        ],
    )


def _values(result: AnalyticalResult, label: str) -> list[float]:
    return [value.value for value in result.values if value.label == label]


def _periods(result: AnalyticalResult, label: str) -> list[str]:
    return [
        value.period.end.isoformat()
        for value in result.values
        if value.label == label and value.period is not None
    ]


def _count(result: AnalyticalResult, label: str) -> int:
    values = [value.value for value in result.values if value.label == label]
    if len(values) != 1:
        raise ValueError(f"Expected one count labelled {label!r}")
    return int(values[0])


def _turn_one_actual() -> Actual:
    result = co_movement(
        _observations((10.0, 9.0, 8.0, 8.5)),
        RATE,
        _observations((100.0, 105.0, 105.0, 104.0)),
        STOCK,
        start=date(2021, 1, 1),
        end=MONTHS[-1],
        driver_label=RATE_LABEL,
        target_label=CREDIT_LABEL,
        input_refs=["synthetic_fixed_input"],
    )
    change_label = f"{RATE_LABEL} month-over-month change"
    credit_change_label = f"{CREDIT_LABEL} month-over-month change"
    highlighted = result.parameters.get("highlighted_periods")
    if not isinstance(highlighted, dict):
        raise ValueError("Co-movement result did not record highlighted periods")
    highlighted_periods = highlighted.get(f"{RATE_LABEL} fell and {CREDIT_LABEL} did not rise")
    if not isinstance(highlighted_periods, list):
        raise ValueError("Co-movement result recorded invalid highlighted periods")
    return {
        "status": result.status.value,
        "transition_periods": _periods(result, change_label),
        "rate_changes_percentage_points": _values(result, change_label),
        "credit_changes_million_try": _values(result, credit_change_label),
        "counts": {
            "transitions": _count(result, "consecutive monthly transitions compared"),
            "rate_fell": _count(result, f"transitions where {RATE_LABEL} fell"),
            "credit_rose_when_rate_fell": _count(
                result, f"transitions where {RATE_LABEL} fell and {CREDIT_LABEL} rose"
            ),
            "credit_did_not_rise_when_rate_fell": _count(
                result,
                f"transitions where {RATE_LABEL} fell and {CREDIT_LABEL} did not rise",
            ),
        },
        "highlighted_periods": highlighted_periods,
        "stock_not_disbursement": any(
            "not new lending or disbursement" in text for text in result.limitations
        ),
        "non_causal": any(
            "not evidence" in text and "caused" in text for text in result.limitations
        ),
    }


def _turn_two_actual() -> Actual:
    source = _table(credit=(100.0, 105.0, 110.0, 115.0))
    before = source.model_dump(mode="json")
    nominal = [value for value in source.values if value.label == CREDIT_LABEL]
    result = deflate(
        nominal,
        _observations((100.0, 110.0, 110.0, 115.0)),
        CPI,
        column_label=CREDIT_LABEL,
        index_id=CPI_ID,
        reference_end=MONTHS[-1],
    )
    combined = [*source.values, *result.values]
    untouched_rate = [value for value in combined if value.label == RATE_LABEL]
    return {
        "source_unchanged": source.model_dump(mode="json") == before,
        "existing_prefix_preserved": combined[: len(source.values)] == source.values,
        "untouched_rate_values": [value.value for value in untouched_rate],
        "real_values_million_try": [value.value for value in result.values],
        "real_periods": [value.period.end.isoformat() for value in result.values if value.period],
        "new_label": result.label,
        "operation": result.transformation.operation,
        "formula": result.transformation.parameters["formula"],
    }


def _turn_three_actual() -> Actual:
    source = _table()
    before = source.model_dump(mode="json")
    added = add_monthly_series(
        source,
        _observations((200.0, 205.0, 207.5, 210.0)),
        KFE,
        series_id=KFE_ID,
    )
    combined = [*source.values, *added.values]
    return {
        "source_unchanged": source.model_dump(mode="json") == before,
        "existing_prefix_preserved": combined[: len(source.values)] == source.values,
        "existing_value_count": len(source.values),
        "combined_value_count": len(combined),
        "added_periods": [value.period.end.isoformat() for value in added.values if value.period],
        "added_values": [value.value for value in added.values],
        "missing_periods": [item.isoformat() for item in added.missing_periods],
        "join": added.transformation.parameters["join"],
        "fill": added.transformation.parameters["fill"],
    }


def _relationship_actual() -> Actual:
    result = compare_table_directions(
        _table(),
        driver_column=RATE_LABEL,
        target_column=CREDIT_LABEL,
        driver_direction="down",
        target_direction="up",
    )
    transform = result.evidence.transformations[-1] if result.evidence else None
    if transform is None:
        raise ValueError("Relationship result did not record its transformation")
    return {
        "status": result.status.value,
        "counts": transform.parameters["counts"],
        "eligible_periods": transform.parameters["eligible_periods"],
        "matching_periods": transform.parameters["joint_periods"],
        "non_causal": any("not an identified causal effect" in text for text in result.limitations),
    }


def _abstention_actual() -> Actual:
    unknown_stock = SeriesSemantics(
        unit="TRY",
        scale=Scale.UNKNOWN,
        frequency=Frequency.MONTHLY,
        observation=StockFlow.STOCK,
        cumulative=CumulativeKind.NONE,
    )
    result = co_movement(
        _observations((10.0, 9.0, 8.0, 8.5)),
        RATE,
        _observations((100.0, 105.0, 105.0, 104.0)),
        unknown_stock,
        start=date(2021, 1, 1),
        end=MONTHS[-1],
        driver_label=RATE_LABEL,
        target_label=CREDIT_LABEL,
        input_refs=["synthetic_fixed_input"],
    )
    return {
        "status": result.status.value,
        "reason": result.reason,
        "values": len(result.values),
        "unresolved_semantics": result.unresolved_semantics,
    }


