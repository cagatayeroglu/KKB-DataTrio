"""Operator-run harvest of FinTürk's own listing (not a unit test).

    python tests/manual/harvest_bddk_finturk_directory.py

FinTürk is BDDK's province breakdown: seven tables, one row per province, one answer per
table and quarter. This script reads the page's own option lists (tables with their unit
label, provinces, quarters, bank groups) and asks each table once, for the latest quarter
and every province, to learn its column names. It keeps what a person reads there and no
observation value. The listing is written as `src/kkb_agent/ingest/bddk_finturk_directory.py`,
pinned by its own SHA-256. Eight public requests, one a second.
"""

from __future__ import annotations

import hashlib
import html
import json
import re
import subprocess
import time
from pathlib import Path
from urllib.parse import urlencode

PAGE = "https://www.bddk.org.tr/BultenFinturk"
ENDPOINT = "https://www.bddk.org.tr/BultenFinturk/tr/Home/VeriGetir"
TARGET = Path(__file__).resolve().parents[2] / "src/kkb_agent/ingest/bddk_finturk_directory.py"
SECTOR = "10001"
EVERY_PROVINCE = "HEPSİ"
#: The identity columns every answer starts with; the value columns follow them.
IDENTITY_COLUMNS = 5
SELECT = r'<select[^>]*id="%s"[^>]*>(.*?)</select>'
OPTION = re.compile(r'<option[^>]*value="([^"]*)"[^>]*>(.*?)</option>', re.S)
LABEL = re.compile(r"^(?P<title>.+?)\s*\((?P<unit>[^()]*)\)(?P<rest>.*)$")


def curl(*args: str) -> bytes:
    """One request; a transient transport failure (TLS reset, timeout) is asked again."""
    for attempt in range(4):
        done = subprocess.run(  # noqa: S603 - fixed argv, no shell
            ["curl", "-s", "--max-time", "90", "-H", "User-Agent: Mozilla/5.0", *args],  # noqa: S607
            capture_output=True,
            check=False,
        )
        time.sleep(1.0)
        if done.returncode == 0 and done.stdout:
            return done.stdout
        time.sleep(2.0 * (attempt + 1))
    raise RuntimeError("the source did not answer after four attempts")


def options(page: str, name: str) -> list[tuple[str, str]]:
    block = re.search(SELECT % name, page, re.S)
    if block is None:
        raise RuntimeError(f"the page no longer carries its {name} list")
    return [
        (value, " ".join(html.unescape(text).split())) for value, text in OPTION.findall(block[1])
    ]


def ask(table: str, period: str) -> dict[str, object]:
    body = urlencode(
        [
            ("tabloNo", table),
            ("donem", period),
            ("tarafList[0]", SECTOR),
            ("sehirList[0]", EVERY_PROVINCE),
        ]
    )
    answer = json.loads(curl("-X", "POST", ENDPOINT, "--data", body).decode("utf-8"))
    if answer.get("success") is not True:
        raise RuntimeError(f"table {table} did not answer for {period}")
    return answer["Json"]


def main() -> int:
    page = curl(PAGE).decode("utf-8", errors="replace")
    periods = [value for value, _ in options(page, "ddlDonem")]
    latest = periods[0]
    provinces = [value for value, _ in options(page, "ddlSehir") if value != EVERY_PROVINCE]
    tables: dict[str, object] = {}
    for number, label in options(page, "ddlTablo"):
        answer = ask(number, latest)
        names = list(answer["colNames"])
        rows = answer["data"]["rows"]
        tables[number] = {
            "label": label,
            "columns": names[IDENTITY_COLUMNS:],
            "identity": names[:IDENTITY_COLUMNS],
            "provinces": sorted({row["cell"][3] for row in rows}),
        }
        print(f"{number} {label}: {len(names) - IDENTITY_COLUMNS} columns, {len(rows)} provinces")
    payload = {
        "source": ENDPOINT,
        "page": PAGE,
        "side": "SEKTÖR",
        "latest_period_at_harvest": latest,
        "first_period": periods[-1],
        "provinces": provinces,
        "tables": tables,
    }
    canonical = json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    digest = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    body = json.dumps(payload, ensure_ascii=False, sort_keys=True, indent=1)
    TARGET.write_text(
        '"""GENERATED by tests/manual/harvest_bddk_finturk_directory.py; do not edit by hand.\n\n'
        "FinTürk's own listing: tables with their unit label, column names and provinces, for\n"
        "the sector aggregate. No observation value is stored; `DIRECTORY_SHA256` pins the\n"
        'exact content.\n"""\n\n'
        "# ruff: noqa: E501 - the listing keeps the source's own labels, however long\n"
        "import json\nfrom typing import Any, Final\n\n"
        f'DIRECTORY_SHA256: Final = "{digest}"\n'
        "DIRECTORY_JSON: Final = r'''" + body + "'''\n"
        "DIRECTORY: Final[dict[str, Any]] = json.loads(DIRECTORY_JSON)\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {TARGET.name}: {len(tables)} tables, sha256 {digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
