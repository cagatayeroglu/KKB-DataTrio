"""Operator-run harvest of EVDS's own datagroup directory (not a unit test).

    python tests/manual/harvest_evds_directory.py

One public request (`categories/withDatagroups/type=json`, about 730 KB, no credentials):
every category and datagroup EVDS lists. What is kept per datagroup is what a person
browsing "Tüm Seriler" reads: code, Turkish and English title, its category path, native
frequency, publisher, the unit field and whether the title marks it archived. No series
and no observation value are stored; a datagroup's series are listed on demand (DEC-177).
The listing is written as `src/kkb_agent/ingest/evds_directory_listing.py`, pinned by its
own SHA-256. Run it again to refresh: a new datagroup becomes a new searchable entry.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
from pathlib import Path
from typing import Any

URL = "https://evds3.tcmb.gov.tr/igmevdsms-dis/categories/withDatagroups/type=json"
TARGET = Path(__file__).resolve().parents[2] / "src/kkb_agent/ingest/evds_directory_listing.py"


def words(value: Any) -> str:
    return " ".join(str(value or "").split())


def main() -> int:
    done = subprocess.run(  # noqa: S603 - fixed argv, no shell
        ["curl", "-s", "--max-time", "120", URL],  # noqa: S607
        capture_output=True,
        check=True,
    )
    categories = json.loads(done.stdout.decode("utf-8"))
    titles = {item["CATEGORY_ID"]: words(item.get("TOPIC_TITLE_TR")) for item in categories}
    parents = {item["CATEGORY_ID"]: item.get("UST_CATEGORY_ID") for item in categories}

    def path(category: int) -> str:
        parts: list[str] = []
        seen: set[int] = set()
        current: Any = category
        while current in titles and current not in seen:
            seen.add(current)
            parts.append(titles[current])
            current = parents.get(current)
        return " > ".join(reversed(parts))

    groups = []
    for category in categories:
        for group in category.get("DATAGROUPS") or []:
            title = words(group.get("DATAGROUP_TYPE"))
            groups.append(
                {
                    "code": words(group.get("DATAGROUP_CODE")),
                    "title": title,
                    "title_eng": words(group.get("DATAGROUP_TYPE_ENG")),
                    "category": path(category["CATEGORY_ID"]),
                    "frequency_str": words(group.get("FREQUENCY_STR")),
                    "data_source": words(group.get("DATASOURCE")),
                    "unit_text": words(group.get("BIRIMI")),
                    "archived": "arşiv" in title.lower().replace("ş", "ş"),
                }
            )
    groups.sort(key=lambda item: item["code"])
    payload = {"source": URL, "groups": groups}
    canonical = json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    digest = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    body = json.dumps(payload, ensure_ascii=False, sort_keys=True, indent=1)
    header = (
        '"""GENERATED by tests/manual/harvest_evds_directory.py; do not edit by hand.\n\n'
        "EVDS's own datagroup directory: codes, titles, category paths, native frequency,\n"
        "publisher and unit field. No series and no observation value is stored (DEC-177);\n"
        "`DIRECTORY_SHA256` pins the exact content.\n"
        '"""\n\n'
        "# ruff: noqa: E501 - the listing keeps the source's own titles, however long\n"
        "import json\n"
        "from typing import Final\n\n"
    )
    TARGET.write_text(
        header
        + f'DIRECTORY_SHA256: Final = "{digest}"\n'
        + "DIRECTORY_JSON: Final = r'''"
        + body
        + "'''\n"
        + "DIRECTORY: Final = json.loads(DIRECTORY_JSON)\n",
        encoding="utf-8",
        newline="\n",
    )
    archived = sum(1 for item in groups if item["archived"])
    with_unit = sum(1 for item in groups if item["unit_text"])
    print(
        f"wrote {TARGET.name}: {len(groups)} datagroups ({archived} archived, "
        f"{with_unit} with a unit field), sha256 {digest}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
