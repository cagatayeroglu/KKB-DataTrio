"""Operator-run harvest of the BDDK weekly bulletin's own listing (not a unit test).

    python tests/manual/harvest_bddk_weekly_directory.py

The weekly bulletin serves each item's history through one stateless public endpoint
(`KiyaslamaJsonGetir`: thirteen weeks ending at a given date, for an item id `<table>.0.<row>`
and a column). This script asks that endpoint, for the latest published week, which item ids
exist in the nine tables the bulletin's own menu lists and which columns each has, and keeps
what a person reads on the page: table title, row label and column label. No observation
value is stored. The listing is written as `src/kkb_agent/ingest/bddk_weekly_directory.py`,
pinned by its own SHA-256. About 700 requests, one every 0.4 s.
"""

from __future__ import annotations

import hashlib
import html
import json
import re
import subprocess
import time
from datetime import date, timedelta
from pathlib import Path

PAGE = "https://www.bddk.org.tr/BultenHaftalik"
ENDPOINT = "https://www.bddk.org.tr/BultenHaftalik/tr/Home/KiyaslamaJsonGetir"
TARGET = Path(__file__).resolve().parents[2] / "src/kkb_agent/ingest/bddk_weekly_directory.py"
TITLE = re.compile(r"^(?P<label>.+) \((?P<currency>[A-Z]{3})\) \[(?P<column>[^\]]+)\] \[(?P<side>[^\]]+)\]$")
MENU = re.compile(r"TabloDegistir\('(\d+)'\).*?<span class=\"text\">([^<]+)</span>", re.S)
MAX_ROWS = 120
MISSES_END_A_TABLE = 8


def curl(*args: str) -> bytes:
    """One request; a transient transport failure (TLS reset, timeout) is asked again."""
    for attempt in range(4):
        done = subprocess.run(  # noqa: S603 - fixed argv, no shell
            ["curl", "-s", "--max-time", "60", "-H", "User-Agent: Mozilla/5.0", *args],  # noqa: S607
            capture_output=True,
            check=False,
        )
        time.sleep(0.4)
        if done.returncode == 0:
            return done.stdout
        time.sleep(2.0 * (attempt + 1))
    raise RuntimeError("the source did not answer after four attempts")


def ask(item: str, column: int, friday: date) -> dict[str, object]:
    body = (
        f"dil=tr&tarih={friday:%d.%m.%Y}&id={item}&parabirimi=TRY&sutun={column}"
        "&gun=90&tarafKodu=10001"
    )
    raw = curl("-X", "POST", ENDPOINT, "-H", "X-Requested-With: XMLHttpRequest", "--data", body)
    try:
        return json.loads(raw.decode("utf-8"))
    except ValueError:
        return {}


def main() -> int:
    page = curl(PAGE).decode("utf-8", errors="replace")
    menu = [html.unescape(title).strip() for _, title in MENU.findall(page)]
    caption = "Milyon TL" if "(Milyon TL)" in page else ""
    today = date.today()
    friday = today - timedelta(days=(today.weekday() - 4) % 7 + 7)  # a week that is published
    tables = []
    for number, title in enumerate(menu, start=1):
        rows, misses = [], 0
        for row in range(1, MAX_ROWS + 1):
            columns: dict[str, str] = {}
            label = None
            for column in (3, 1, 2):
                answer = ask(f"{number}.0.{row}", column, friday)
                found = TITLE.match(str(answer.get("Baslik") or ""))
                if found is None or not answer.get("XEkseni"):
                    if column == 3:
                        break  # no total column: the id does not exist
                    continue
                label = label or found["label"].strip()
                columns[str(column)] = found["column"].strip()
            if not columns:
                misses += 1
                if misses >= MISSES_END_A_TABLE:
                    break
                continue
            misses = 0
            rows.append({"row": row, "label": label, "columns": columns})
        tables.append({"table": number, "title": title, "rows": rows})
        print(f"{number} {title}: {len(rows)} rows", flush=True)
    payload = {"source": ENDPOINT, "unit_caption": caption, "side": "Sektör", "tables": tables}
    canonical = json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    digest = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    body = json.dumps(payload, ensure_ascii=False, sort_keys=True, indent=1)
    TARGET.write_text(
        '"""GENERATED by tests/manual/harvest_bddk_weekly_directory.py; do not edit by hand.\n\n'
        "The BDDK weekly bulletin's own listing: tables, row labels and column labels for the\n"
        "sector aggregate in TL. No observation value is stored; `DIRECTORY_SHA256` pins the\n"
        'exact content.\n"""\n\n'
        "# ruff: noqa: E501 - the listing keeps the source's own labels, however long\n"
        "import json\nfrom typing import Final\n\n"
        f'DIRECTORY_SHA256: Final = "{digest}"\n'
        "DIRECTORY_JSON: Final = r'''" + body + "'''\n"
        "DIRECTORY: Final = json.loads(DIRECTORY_JSON)\n",
        encoding="utf-8",
        newline="\n",
    )
    total = sum(len(table["rows"]) for table in tables)
    print(f"wrote {TARGET.name}: {len(tables)} tables, {total} rows, sha256 {digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
